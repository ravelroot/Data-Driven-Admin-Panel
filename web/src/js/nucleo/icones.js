const atributos = (objeto) =>
  Object.entries(objeto)
    .map(([nome, valor]) => `${nome}="${String(valor).replace(/"/g, "&quot;")}"`)
    .join(" ");

const montarFilhos = (nos) => nos.map(([tag, attrs, filhos]) => `<${tag} ${atributos(attrs)}>${filhos ? montarFilhos(filhos) : ""}</${tag}>`).join("");

const cache = new Map();

export const icone = (nome, classe = "") => {
  const chave = `${nome}|${classe}`;
  if (cache.has(chave)) return cache.get(chave);
  const no = ICONES[nome] ?? ICONES.ponto;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" class="lucide${classe ? ` ${classe}` : ""}" aria-hidden="true" focusable="false">${montarFilhos(no)}</svg>`;
  cache.set(chave, svg);
  return svg;
};

export const existeIcone = (nome) => Object.hasOwn(ICONES, nome);

export const hidratarIcones = (raiz = document) => {
  for (const elemento of raiz.querySelectorAll("i[data-icone]")) {
    const classe = elemento.getAttribute("class") || "";
    const modelo = document.createElement("template");
    modelo.innerHTML = icone(elemento.dataset.icone, classe);
    elemento.replaceWith(modelo.content.firstElementChild);
  }
};

