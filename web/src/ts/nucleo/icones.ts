const atributos = (objeto: Record<string, string | number | undefined>): string =>
  Object.entries(objeto)
    .map(([nome, valor]) => `${nome}="${String(valor).replace(/"/g, "&quot;")}"`)
    .join(" ");

type No = readonly [string, Record<string, string | number | undefined>, ReadonlyArray<No>?];

const montarFilhos = (nos: ReadonlyArray<No>): string => nos.map(([tag, attrs, filhos]) => `<${tag} ${atributos(attrs)}>${filhos ? montarFilhos(filhos) : ""}</${tag}>`).join("");

const cache = new Map<string, string>();

export const icone = (nome: string, classe = ""): string => {
  const chave = `${nome}|${classe}`;
  const salvo = cache.get(chave);
  if (salvo) return salvo;
  const no = ICONES[nome] ?? ICONES.ponto;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" class="lucide${classe ? ` ${classe}` : ""}" aria-hidden="true" focusable="false">${montarFilhos(no as unknown as ReadonlyArray<No>)}</svg>`;
  cache.set(chave, svg);
  return svg;
};

export const existeIcone = (nome: string): boolean => Object.hasOwn(ICONES, nome);

export const hidratarIcones = (raiz: ParentNode = document): void => {
  for (const elemento of raiz.querySelectorAll<HTMLElement>("i[data-icone]")) {
    const classe = elemento.getAttribute("class") || "";
    const modelo = document.createElement("template");
    modelo.innerHTML = icone(elemento.dataset.icone ?? "ponto", classe);
    const svg = modelo.content.firstElementChild;
    if (svg) elemento.replaceWith(svg);
  }
};

